const assert=require('node:assert/strict');
const {view,sort,currentJudge}=require('./price-effect.js');
const child={child:'C',start:'2026-10-13',original_price:10,actual_price:11};
const b={site:'A:US',parent:'P',batch_week:'2026-10-12',owners:['李漉','陈梦怡'],children:[child]};
const effect={signature:[['C','2026-10-13',10,11]],base_start:'2026-09-28',observation_end:'2026-11-01',status:'需关注',profit_delta:5,units_change:-.2};
const weekly={parents:[{site:'A:US',parent:'P',batch_week:'2026-10-12',parent_name:'父单',effect}]};
const filter={manager:'all',country:'US',start:'2026-10-26',end:'2026-11-01',latestWeek:'2026-11-01',countryOf:s=>s.split(':')[1]};
assert.equal(view([b],weekly,filter).parents.length,1);
assert.equal(view([b],weekly,{...filter,manager:'陈梦怡'}).parents.length,1);
assert.equal(view([b],weekly,{...filter,manager:'陈芳志'}).parents.length,0);
assert.equal(view([b],weekly,{...filter,country:'UK'}).parents.length,0);
assert.equal(view([b],weekly,{...filter,end:'2026-10-25'}).historyMissing,true);
assert.equal(view([b],weekly,{...filter,end:'2026-10-25',latestWeek:'2026-10-25'}).parents[0].effect.status,'待观察');
const next={...b,batch_week:'2026-10-19',children:[{...child,child:'D',start:'2026-10-20'}]};
assert.equal(view([b,next],weekly,filter).parents.length,1);
assert.equal(sort([{effect:{status:'有效候选',profit_delta:5}},{effect:{status:'无效',profit_delta:-3}}],'risk')[0].effect.status,'无效');
const confirmed={children:[{comparability_confirmed:true,interference_confirmed:true}]};
const comparable={status:'待核验',reason:'需确认对照及汇率、广告、促销、断货干扰',observation_end:'2026-10-25',profit_delta:5,before:{asp:10,margin:.1},after:{asp:9,margin:.2}};
assert.equal(currentJudge(comparable,confirmed).status,'需关注');
assert.equal(currentJudge({...comparable,profit_delta:-1,after:{asp:12,margin:.08}},confirmed).status,'无效');
assert.equal(currentJudge({...comparable,status:'待核验',reason:'部分执行报表读取失败'},confirmed).status,'待核验');
assert.equal(currentJudge(comparable,{children:[{comparability_confirmed:false,interference_confirmed:true}]}).status,'待核验');
console.log('pricing effect view checks passed');
